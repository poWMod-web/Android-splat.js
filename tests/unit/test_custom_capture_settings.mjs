import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DistanceCaptureTrigger } from '../../app/js/xr-distance.js';
import { parseCycleCount, parseLODCount, maxLODLevels, buildLODPlan } from '../../app/js/training-settings.js';

const trigger = new DistanceCaptureTrigger(.10);
assert.equal(trigger.sample([0, 0, 0]), false, 'enabling auto establishes a baseline, not an immediate shot');
for (let i = 0; i < 1000; i++) assert.equal(trigger.sample([0, 0, 0]), false, 'stationary camera never fires regardless of elapsed frames');
assert.equal(trigger.sample([.04, 0, 0]), false);
assert.equal(trigger.sample([.08, 0, 0]), false);
assert.equal(trigger.sample([.10, 0, 0]), true);
trigger.setSpacingMeters(.25);
assert.equal(trigger.spacingMeters, .25);
assert.equal(trigger.distanceSinceCapture, 0, 'editing spacing resets the path baseline');
assert.equal(trigger.sample([.10, 0, 0]), false);
assert.equal(trigger.sample([.35, 0, 0]), true, 'the updated spacing is live');
assert.throws(() => trigger.setSpacingMeters(0), /positive meters/);
trigger.setSpacingMeters(.10);
trigger.reset();
assert.equal(trigger.sample([0, 0, 0]), false);
assert.equal(trigger.sample([.10, 0, 0]), true);
trigger.captured([.10, 0, 0]);
assert.equal(trigger.sample([.10, 0, 0]), false);
assert.equal(trigger.sample([.05, 0, 0]), false);
assert.equal(trigger.sample([.10, 0, 0]), true, 'path length, not net displacement, triggers a photo');
trigger.captured([.10, 0, 0]);
trigger.breakContinuity();
assert.equal(trigger.sample([4, 0, 0]), false, 'recovered tracking must not count an unobserved jump');
assert.equal(trigger.sample([4.10, 0, 0]), true);
trigger.reset();
assert.equal(trigger.sample([0, 0, 0]), false);
for (let i = 0; i < 100; i++) assert.equal(trigger.sample([i % 2 ? .001 : 0, 0, 0]), false, 'sub-noise-floor pose jitter is ignored');
assert.equal(parseCycleCount(''), 0);
assert.equal(parseCycleCount('12345'), 12345);
assert.equal(parseCycleCount('8000'), 8000);
for (const v of ['0', '-1', '1.5', '1000001', 'NaN', 'Infinity']) assert.throws(() => parseCycleCount(v), /Cycles/);
assert.equal(maxLODLevels(600000), 0);
assert.equal(maxLODLevels(1000000), 2);
assert.equal(maxLODLevels(2000000), 3);
assert.equal(maxLODLevels(4000000), 4);
assert.equal(parseLODCount('', 1000000), 0);
assert.equal(parseLODCount('2', 1000000), 2);
assert.throws(() => parseLODCount('3', 1000000), /1–2/);
assert.throws(() => parseLODCount('1.5', 1000000), /LOD/);
assert.equal(buildLODPlan(600000, 0, 20000), null);
assert.deepEqual(buildLODPlan(1000000, 0, 20000).levels, [250000, 500000, 1000000]);
assert.deepEqual(buildLODPlan(1000000, 2, 12345).levels, [250000, 500000, 1000000]);
assert.deepEqual(buildLODPlan(1000000, 1, 12345).levels, [500000, 1000000]);
assert.deepEqual(buildLODPlan(4000000, 3, 12345).levels, [500000, 1000000, 2000000, 4000000]);
assert.ok(buildLODPlan(1000000, 2, 100).polish <= 12);
const capture = readFileSync(new URL('../../app/js/xr-capture.js', import.meta.url), 'utf8');
assert.match(capture, /auto: false/);
assert.doesNotMatch(capture, /data-action="auto" checked/);
assert.doesNotMatch(capture, /AUTO_INTERVAL_MS|lastAutoTime|AUTO_MIN_ROTATION|shouldAutoCapture/);
assert.match(capture, /state\.auto && state\.autoRunning && state\.distanceTrigger\.sample\(position\)/);
assert.match(capture, /type="number" data-action="distance"/);
assert.match(capture, /value="\$\{spacingCm\}"/);
assert.match(capture, /CAPTURE_SPACING_KEY/);
const controller = readFileSync(new URL('../../app/js/app.js', import.meta.url), 'utf8');
assert.match(controller, /buildLODPlan\(st\.splats, st\.lodLevels \|\| 0, S\.maxIters\)/);
assert.match(controller, /st\.iters = cycleCount/);
assert.match(controller, /S\.commitSettings && !S\.commitSettings\(\)/);
const html = readFileSync(new URL('../../app/index.html', import.meta.url), 'utf8');
assert.match(html, /<select id="set-iters"[\s\S]*?<option value="10000">10,000<\/option>[\s\S]*?<option value="50000">50,000<\/option>/);
assert.match(controller, /10000, 20000, 30000, 40000, 50000/);
assert.match(controller, /camera-orbit/);
assert.match(html, /id="set-lod-count" type="number"/);
assert.match(html, /<option value="">Off<\/option>\s*<option value="1">On<\/option>/);
assert.match(controller, /lod: false/);
console.log('manual default, distance-only travel, custom cycles and requested LOD plans: passed');
