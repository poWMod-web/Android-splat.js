import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { validateDataset, filterDataset, measuredSeeds, cameraForFile, storedCapture, datasetFromSelection } from '../../app/js/xr-dataset.js';
import { parseCameras, reconFromKnownCameras } from '../../src/io/cameras.js';

const camerasFixture = new URL('../../data/synthetic/cameras.json', import.meta.url);
if (!existsSync(camerasFixture)) {
  console.log('SKIP missing reference fixture data/synthetic/cameras.json');
  process.exit(0);
}
const json = JSON.parse(readFileSync(camerasFixture));
const files = json.cameras.map((c) => new File(['image'], c.image, { type: 'image/png' }));
const point = (i) => ({ X: [i / 10, 0, 1], rgb: [.3, .4, .5] });
const pointsByFrame = Object.fromEntries(files.map((f, i) => [f.name, [point(i)]]));
const dataset = { files, transforms: json, points: Object.values(pointsByFrame).flat(), pointsByFrame, metadata: { seedSource: 'depth' } };
assert.equal(validateDataset(dataset), dataset);
assert.equal(measuredSeeds(dataset).length, 12);
assert.equal(measuredSeeds({ points: [point(0)] }).length, 0);
assert.throws(() => validateDataset({ ...dataset, files: files.slice(0, 2) }), /at least 3/);
assert.throws(() => validateDataset({ ...dataset, files: [files[0], files[0], files[2]] }), /unique/);
assert.throws(() => validateDataset({ ...dataset, files: [...files.slice(0, 3), new File(['x'], 'unknown.png', { type: 'image/png' })] }), /No known camera/);
assert.throws(() => validateDataset({ ...dataset, points: [{ X: [NaN, 0, 0], rgb: [1, 1, 1] }] }), /finite/);
const broken = structuredClone(json); broken.cameras[0].fx = 0;
assert.throws(() => validateDataset({ ...dataset, transforms: broken }), /focal/);
const selected = files.slice(1, 5).map((f) => f.name);
const filtered = filterDataset(dataset, selected);
assert.equal(filtered.files.length, 4);
assert.equal(filtered.transforms.cameras.length, 4);
assert.equal(filtered.points.length, 4);
assert.equal(filtered.files[0].name, 'synthetic_01.png');
assert.equal(validateDataset(filtered), filtered);
assert.equal(filterDataset(dataset, []).files.length, 0);
const c = cameraForFile(dataset, files[0].name);
assert.ok(c.position.every((v, i) => Math.abs(v - json.cameras[0].camera_center_world[i]) < 1e-7));
const stored = storedCapture(dataset);
assert.equal(stored.kind, 'ar'); assert.equal(stored.files[0].blob, files[0]);
assert.equal(stored.transforms, json); assert.equal(stored.pointsByFrame, pointsByFrame);
const cameraFile = new File([JSON.stringify(json)], 'cameras.json', { type: 'application/json' });
const seedFile = new File([JSON.stringify({ points: dataset.points })], 'seed_points.json', { type: 'application/json' });
const imported = await datasetFromSelection([...files, cameraFile, seedFile]);
assert.equal(imported.files.length, 12); assert.equal(imported.points.length, 12); assert.equal(imported.metadata.imported, true);
const ownedSeeds = new File([JSON.stringify({ points: dataset.points, pointsByFrame })], 'seed_points.json', { type: 'application/json' });
const roundTrip = await datasetFromSelection([...files, cameraFile, ownedSeeds]);
const dropped = filterDataset(roundTrip, files.slice(1, 5).map((f) => f.name));
assert.equal(dropped.points.length, 4);
assert.ok(dropped.points.every((p) => p.frameName !== files[0].name));
assert.deepEqual(dropped.points.map((p) => p.X), dataset.points.slice(1, 5).map((p) => p.X));
const metadataFile = new File([JSON.stringify({ pointsByFrame })], 'capture.json', { type: 'application/json' });
const legacyRoundTrip = await datasetFromSelection([...files, cameraFile, seedFile, metadataFile]);
assert.equal(filterDataset(legacyRoundTrip, files.slice(1, 5).map((f) => f.name)).points.length, 4);
assert.throws(() => validateDataset({ ...dataset, pointsByFrame: { [files[0].name]: [{ X: [NaN, 0, 0], rgb: [1, 1, 1] }] } }), /Per-frame/);
const skewed = structuredClone(json); skewed.cameras[0].skew = .25;
assert.throws(() => validateDataset({ ...dataset, transforms: skewed }), /skew/);
const frames = files.map((f) => ({ name: f.name, srcW: 640, srcH: 480, fw: 320, fh: 240 }));
const recon = reconFromKnownCameras(frames, parseCameras(json), { points: dataset.points });
assert.equal(recon.known, true); assert.equal(recon.cams.length, 12);
assert.equal(recon.cams[0].f, 310); assert.equal(recon.cams[0].cx, 160);
assert.equal(recon.points, dataset.points);
const random = reconFromKnownCameras(frames, parseCameras(json), { seedCount: 50 });
assert.equal(random.points.length, 50); assert.equal(random.known, true);
const controller = readFileSync(new URL('../../app/js/app.js', import.meta.url), 'utf8');
assert.match(controller, /if \(knownCapture\)[\s\S]*?session\.useKnownCameras[\s\S]*?\} else \{\s*await session\.solve/);
assert.match(controller, /camOpt: false, aspectOpt: false/);
assert.match(controller, /const files = capture \? \[\.\.\.capture\.files\]/);
console.log('known cameras, frame filtering, seed provenance, persistence and import: passed');
